import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'maps-config.js');
const apiKey = String(process.env.SANPO_GOOGLE_MAPS_API_KEY || '').trim();
if (!apiKey) {
  console.error('SANPO_GOOGLE_MAPS_API_KEY is required.');
  process.exit(1);
}
const config = {
  apiKey,
  language: String(process.env.SANPO_GOOGLE_MAPS_LANGUAGE || 'ja'),
  region: String(process.env.SANPO_GOOGLE_MAPS_REGION || 'JP'),
  version: String(process.env.SANPO_GOOGLE_MAPS_VERSION || 'weekly')
};
const source = `// Generated by tools/write-maps-config.mjs. Do not duplicate the key elsewhere.\nwindow.SANPO_GOOGLE_MAPS_CONFIG = Object.freeze(${JSON.stringify(config, null, 2)});\n`;
fs.writeFileSync(output, source);
console.log(`Wrote ${path.relative(root, output)}`);
