import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const packageJson = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
const versions = {
  webComponents: packageJson.devDependencies['@carbon/web-components'],
  icons: packageJson.devDependencies['@carbon/icons'],
  plexSans: packageJson.devDependencies['@ibm/plex-sans'],
  plexSansJp: packageJson.devDependencies['@ibm/plex-sans-jp']
};

const carbonVendor = join(root, 'assets', 'vendor', 'carbon');
const plexVendor = join(root, 'assets', 'vendor', 'ibm-plex');
const plexFonts = join(plexVendor, 'fonts');
await Promise.all([mkdir(carbonVendor, { recursive: true }), mkdir(plexFonts, { recursive: true })]);

await build({
  entryPoints: [join(root, 'assets', 'js', 'carbon-entry.js')],
  outfile: join(carbonVendor, 'carbon-entry.min.js'),
  bundle: true,
  define: {
    __CARBON_WEB_COMPONENTS_VERSION__: JSON.stringify(versions.webComponents),
    __CARBON_ICONS_VERSION__: JSON.stringify(versions.icons),
    __IBM_PLEX_SANS_VERSION__: JSON.stringify(versions.plexSans),
    __IBM_PLEX_SANS_JP_VERSION__: JSON.stringify(versions.plexSansJp)
  },
  format: 'esm',
  legalComments: 'eof',
  minify: true,
  sourcemap: false,
  target: ['es2020']
});

const fontCopies = [
  ['@ibm/plex-sans/fonts/complete/woff2/IBMPlexSans-Regular.woff2', 'IBMPlexSans-Regular.woff2'],
  ['@ibm/plex-sans/fonts/complete/woff2/IBMPlexSans-SemiBold.woff2', 'IBMPlexSans-SemiBold.woff2'],
  ['@ibm/plex-sans-jp/fonts/complete/woff2/hinted/IBMPlexSansJP-Regular.woff2', 'IBMPlexSansJP-Regular.woff2'],
  ['@ibm/plex-sans-jp/fonts/complete/woff2/hinted/IBMPlexSansJP-SemiBold.woff2', 'IBMPlexSansJP-SemiBold.woff2']
];

for (const [source, destination] of fontCopies) {
  await copyFile(join(root, 'node_modules', ...source.split('/')), join(plexFonts, destination));
}

const fontCss = `/* Generated by npm run build:carbon from the pinned official IBM Plex packages. */
@font-face {
  font-family: "IBM Plex Sans";
  src: url("./fonts/IBMPlexSans-Regular.woff2") format("woff2");
  font-style: normal;
  font-weight: 400;
  font-display: swap;
}

@font-face {
  font-family: "IBM Plex Sans";
  src: url("./fonts/IBMPlexSans-SemiBold.woff2") format("woff2");
  font-style: normal;
  font-weight: 600 700;
  font-display: swap;
}

@font-face {
  font-family: "IBM Plex Sans JP";
  src: url("./fonts/IBMPlexSansJP-Regular.woff2") format("woff2");
  font-style: normal;
  font-weight: 400;
  font-display: swap;
}

@font-face {
  font-family: "IBM Plex Sans JP";
  src: url("./fonts/IBMPlexSansJP-SemiBold.woff2") format("woff2");
  font-style: normal;
  font-weight: 600 700;
  font-display: swap;
}
`;
await writeFile(join(plexVendor, 'plex.css'), fontCss, 'utf8');

await Promise.all([
  copyFile(join(root, 'node_modules', '@carbon', 'web-components', 'LICENSE'), join(carbonVendor, 'LICENSE-web-components.txt')),
  copyFile(join(root, 'node_modules', '@carbon', 'icons', 'LICENSE'), join(carbonVendor, 'LICENSE-icons.txt')),
  copyFile(join(root, 'node_modules', '@ibm', 'plex-sans', 'LICENSE.txt'), join(plexVendor, 'LICENSE.txt')),
  copyFile(join(root, 'node_modules', '@ibm', 'plex-sans-jp', 'LICENSE.txt'), join(plexVendor, 'LICENSE-jp.txt'))
]);

console.log(`Carbon assets built: Web Components ${versions.webComponents}, Icons ${versions.icons}, Plex ${versions.plexSans}/${versions.plexSansJp}`);
